    private void btnAgregarEstadoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarEstadoActionPerformed
        String nombre = txtEstado.getText().trim();

        if (nombre.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Ingrese un nombre para el estado."
            );
            return;
        }

        if (listaEstados.existe(nombre)) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "El estado '" + nombre + "' ya existe."
            );
            return;
        }

        listaEstados.insertar(nombre);

        dfa.agregarEstado(nombre);

        txtEstados.setText(listaEstados.obtenerTexto());

        listaEstados.llenarCombo(cmbEstadoInicial);
        listaEstados.llenarCombo(cmbOrigen);
        listaEstados.llenarCombo(cmbDestino);

        marcarComoNoValidado();
        
        txtEstado.setText("");
        txtEstado.requestFocus();
    }//GEN-LAST:event_btnAgregarEstadoActionPerformed

