    private void btnAgregarTransicionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarTransicionActionPerformed
        if (cmbOrigen.getSelectedItem() == null) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Debe agregar estados primero."
        );

        return;
    }

    if (cmbSimbolo.getSelectedItem() == null) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Debe agregar símbolos primero."
        );

        return;
    }

    if (cmbDestino.getSelectedItem() == null) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Debe agregar estados primero."
        );

        return;
    }

    String origen =
            cmbOrigen.getSelectedItem().toString();

    String simbolo =
            cmbSimbolo.getSelectedItem().toString();

    String destino =
            cmbDestino.getSelectedItem().toString();

    if (listaTransiciones.existe(origen, simbolo)) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Ya existe una transición para "
                + "(" + origen + ", " + simbolo + ")."
        );

        return;
    }

    listaTransiciones.insertar(
            origen,
            simbolo,
            destino
        );

    dfa.agregarTransicion(
            origen,
            simbolo,
            destino
        );

    txtTransiciones.setText(
            listaTransiciones.obtenerTexto()
    );
    
    marcarComoNoValidado();
    }//GEN-LAST:event_btnAgregarTransicionActionPerformed

    private void btnValidarDFAActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnValidarDFAActionPerformed
        String resultado = validador.validar(dfa);

        javax.swing.JOptionPane.showMessageDialog(
                this,
                resultado
        );

        if (resultado.equals("DFA válido.")) {

            dfaValidado = true;
            btnGuardarDFA.setEnabled(true);

}    }//GEN-LAST:event_btnValidarDFAActionPerformed

    private void btnGuardarDFAActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarDFAActionPerformed
         if (!dfaValidado) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Debe validar el DFA antes de guardarlo."
        );

        return;
    }

    ventanaPrincipal.guardarDFA(dfa);

    dispose();
    }//GEN-LAST:event_btnGuardarDFAActionPerformed

